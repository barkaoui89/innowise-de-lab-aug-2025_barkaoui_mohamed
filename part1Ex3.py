# the first list
fruits = ["apple", "banana"]
print("first list:", fruits)

# 1. Add "orange" to the end
fruits.append("orange")
print("when adding 'orange':", fruits)

# 2. Insert "grape" at index 1
fruits.insert(1, "grape")
print("insert 'grape' at index 1:", fruits)

# 3. remove "banana"
fruits.remove("banana")
print("when removing 'banana':", fruits)

# 4. Sort the list
fruits.sort()
print("after sorting:", fruits)

# 5. Reverse the list
fruits.reverse()
print("after reversing:", fruits)
